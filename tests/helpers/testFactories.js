/**
 * Create batch of test tokens
 *
 * @param {number} count - Number of tokens to create
 * @param {Object} overrides - Properties to override
 * @returns {Array} Array of token data
 */
export function createTestTokenBatch(count = 10, overrides = {}) {
  return Array(count).fill(null).map(() => createTestToken(overrides));
}

/**
 * Create mixed category token batch
 *
 * @param {number} count - Number of tokens to create
 * @returns {Array} Array of tokens with different categories
 */
export function createMixedCategoryTokens(count = 12) {
  const factories = [
    createColorToken,
    createSpacingToken,
    createTypographyToken,
    createShadowToken
  ];

  return Array(count).fill(null).map((_, index) => {
    const factory = factories[index % factories.length];
    return factory();
  });
}


/**
 * Test Data Factories
 *
 * Helper functions for generating test data with realistic values.
 * Use these factories in tests to create consistent, valid test data.
 */

/**
 * Generate unique identifier for test data
 */
export function generateTestId() {
  return `test-${Date.now()}-${Math.random().toString(36).substr(2, 9)}`;
}

/**
 * Create test token data
 *
 * @param {Object} overrides - Properties to override defaults
 * @returns {Object} Token data
 */
export function createTestToken(overrides = {}) {
  const defaults = {
    name: `token-${generateTestId()}`,
    value: `#${Math.floor(Math.random() * 16777215).toString(16).padStart(6, '0')}`,
    category: 'color',
    description: 'Test token generated by test factory'
  };

  return { ...defaults, ...overrides };
}

/**
 * Create test color token
 */
export function createColorToken(overrides = {}) {
  const colors = ['#FF0000', '#00FF00', '#0000FF', '#FFFF00', '#FF00FF', '#00FFFF'];
  const colorNames = ['primary', 'secondary', 'accent', 'background', 'foreground', 'border'];

  return createTestToken({
    name: `color-${colorNames[Math.floor(Math.random() * colorNames.length)]}-${generateTestId()}`,
    value: colors[Math.floor(Math.random() * colors.length)],
    category: 'color',
    ...overrides
  });
}


/**
 * Create test typography token
 */
export function createTypographyToken(overrides = {}) {
  const fonts = ['Inter', 'Roboto', 'Open Sans', 'Lato', 'Montserrat'];
  const sizes = ['12px', '14px', '16px', '18px', '20px', '24px', '32px'];
  const weights = ['400', '500', '600', '700', '800'];

  const type = Math.random() > 0.5 ? 'font-family' : Math.random() > 0.5 ? 'font-size' : 'font-weight';

  let value;
  if (type === 'font-family') {
    value = fonts[Math.floor(Math.random() * fonts.length)];
  } else if (type === 'font-size') {
    value = sizes[Math.floor(Math.random() * sizes.length)];
  } else {
    value = weights[Math.floor(Math.random() * weights.length)];
  }

  return createTestToken({
    name: `typography-${type}-${generateTestId()}`,
    value,
    category: 'typography',
    ...overrides
  });
}

